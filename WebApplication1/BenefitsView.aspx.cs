        private void LoadActiveBenefits()
        {
            string connStr = WebConfigurationManager.ConnectionStrings["MyDatabaseConnection"].ToString();

            using (SqlConnection conn = new SqlConnection(connStr))
            {
                try
                {
                    conn.Open();

                    // Query the allBenefits view
                    SqlCommand cmd = new SqlCommand("SELECT * FROM allBenefits", conn);
                    cmd.CommandType = CommandType.Text;

                    SqlDataAdapter da = new SqlDataAdapter(cmd);
                    DataTable dt = new DataTable();
                    da.Fill(dt);

                    if (dt.Rows.Count > 0)
                    {
                        gvActiveBenefits.DataSource = dt;
                        gvActiveBenefits.DataBind();
                        gvActiveBenefits.Visible = true;
                        lblNoBenefits.Visible = false; // Hide the "No active benefits" message
                    }
                    else
                    {
                        gvActiveBenefits.Visible = false;
                        lblNoBenefits.Text = "No current active benefits";
                        lblNoBenefits.Visible = true; // Show the message
                    }
                }
                catch (Exception ex)
                {
                    lblError.Text = "Error fetching active benefits: " + ex.Message;
                }
            }
        }
