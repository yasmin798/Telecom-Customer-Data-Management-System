        private void BindServicePlans()
        {
            // Connection string to your database
            string connectionString = WebConfigurationManager.ConnectionStrings["MyDatabaseConnection"].ToString();

            using (SqlConnection conn = new SqlConnection(connectionString))
            {
                try
                {

                    string query = "SELECT * FROM allServicePlans";
                    conn.Open();
                    SqlCommand cmd = new SqlCommand(query, conn);
                    SqlDataAdapter adapter = new SqlDataAdapter(cmd);
                    DataTable dt = new DataTable();

                    //conn.Open();
                    adapter.Fill(dt);


                    GridViewServicePlans.DataSource = dt;
                    GridViewServicePlans.DataBind();
                }
                catch (Exception ex)
                {
                    // Handle any errors (optional)
                    Response.Write($"Error: {ex.Message}");
                }
            }
        }
